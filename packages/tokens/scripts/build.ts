/**
 * Compiles the TypeScript tokens into:
 *   dist/tokens.css  – CSS custom properties (primitives + light/dark semantic layer)
 *   dist/theme.css   – Tailwind v4 theme that maps utilities onto those properties
 *   dist/tokens.json – resolved values for docs and non-CSS consumers
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  animation,
  base,
  breakpoint,
  colorValueToCss,
  cssVar,
  duration,
  easing,
  fontFamily,
  fontSize,
  fontWeight,
  keyframes,
  palette,
  radius,
  semanticColors,
  shadow,
  spacingUnit,
  zIndex,
} from "../src/index";
import type { ShadowLayer } from "../src/index";

const outDir = join(import.meta.dirname, "..", "dist");
const banner = "/* Generated by @ledgerly/tokens (scripts/build.ts). Do not edit by hand. */\n";

const decl = (name: string, value: string) => `  ${name}: ${value};`;
const block = (selector: string, lines: string[]) => `${selector} {\n${lines.join("\n")}\n}\n`;

function primitiveDeclarations(): string[] {
  const lines: string[] = [];
  for (const [name, value] of Object.entries(base))
    lines.push(decl(cssVar(`color-${name}`), value));
  for (const [name, steps] of Object.entries(palette)) {
    for (const [step, value] of Object.entries(steps)) {
      lines.push(decl(cssVar(`color-${name}-${step}`), value));
    }
  }
  lines.push(decl(cssVar("space-unit"), spacingUnit));
  for (const [name, value] of Object.entries(radius))
    lines.push(decl(cssVar(`radius-${name}`), value));
  for (const [name, value] of Object.entries(fontFamily))
    lines.push(decl(cssVar(`font-${name}`), value));
  for (const [name, value] of Object.entries(fontWeight)) {
    lines.push(decl(cssVar(`font-weight-${name}`), value));
  }
  for (const [name, value] of Object.entries(fontSize)) {
    lines.push(decl(cssVar(`text-${name}`), value.size));
    lines.push(decl(cssVar(`text-${name}-line-height`), value.lineHeight));
    if ("letterSpacing" in value) {
      lines.push(decl(cssVar(`text-${name}-letter-spacing`), value.letterSpacing));
    }
  }
  for (const [name, layers] of Object.entries(shadow)) {
    const value = layers
      .map((l: ShadowLayer) => {
        const color = `color-mix(in oklab, var(${cssVar(l.color ?? "shadow")}) ${l.opacity}%, transparent)`;
        return `${l.inset ? "inset " : ""}0 ${l.y}px ${l.blur}px ${l.spread}px ${color}`;
      })
      .join(", ");
    lines.push(decl(cssVar(`shadow-${name}`), value));
  }
  for (const [name, value] of Object.entries(duration))
    lines.push(decl(cssVar(`duration-${name}`), value));
  for (const [name, value] of Object.entries(easing))
    lines.push(decl(cssVar(`ease-${name}`), value));
  for (const [name, value] of Object.entries(zIndex)) lines.push(decl(cssVar(`z-${name}`), value));
  return lines;
}

function semanticDeclarations(mode: "light" | "dark"): string[] {
  return Object.entries(semanticColors).map(([name, token]) =>
    decl(cssVar(name), colorValueToCss(token[mode])),
  );
}

function tokensCss(): string {
  return (
    banner +
    block(":root", [
      "  color-scheme: light;",
      "",
      "  /* Primitives */",
      ...primitiveDeclarations(),
      "",
      "  /* Semantic: light */",
      ...semanticDeclarations("light"),
    ]) +
    "\n" +
    block('[data-theme="dark"]', [
      "  color-scheme: dark;",
      "",
      "  /* Semantic: dark */",
      ...semanticDeclarations("dark"),
    ])
  );
}

function themeCss(): string {
  const v = (name: string) => `var(${cssVar(name)})`;
  const lines: string[] = [];

  lines.push("  /* Semantic colors (preferred) */");
  for (const name of Object.keys(semanticColors)) lines.push(decl(`--color-${name}`, v(name)));
  lines.push("", "  /* Palette (for illustration and data viz only) */");
  for (const name of Object.keys(base)) lines.push(decl(`--color-${name}`, v(`color-${name}`)));
  for (const [name, steps] of Object.entries(palette)) {
    for (const step of Object.keys(steps)) {
      lines.push(decl(`--color-${name}-${step}`, v(`color-${name}-${step}`)));
    }
  }

  lines.push("", "  /* Typography */");
  for (const name of Object.keys(fontFamily)) lines.push(decl(`--font-${name}`, v(`font-${name}`)));
  for (const name of Object.keys(fontWeight)) {
    lines.push(decl(`--font-weight-${name}`, v(`font-weight-${name}`)));
  }
  for (const [name, value] of Object.entries(fontSize)) {
    lines.push(decl(`--text-${name}`, v(`text-${name}`)));
    lines.push(decl(`--text-${name}--line-height`, v(`text-${name}-line-height`)));
    if ("letterSpacing" in value) {
      lines.push(decl(`--text-${name}--letter-spacing`, v(`text-${name}-letter-spacing`)));
    }
  }

  lines.push("", "  /* Layout */");
  lines.push(decl("--spacing", v("space-unit")));
  for (const name of Object.keys(radius)) lines.push(decl(`--radius-${name}`, v(`radius-${name}`)));
  for (const name of Object.keys(shadow)) lines.push(decl(`--shadow-${name}`, v(`shadow-${name}`)));

  lines.push("", "  /* Motion */");
  for (const name of Object.keys(easing)) lines.push(decl(`--ease-${name}`, v(`ease-${name}`)));
  for (const [name, value] of Object.entries(animation))
    lines.push(decl(`--animate-${name}`, value));
  for (const [name, frames] of Object.entries(keyframes)) {
    lines.push("", `  @keyframes ${name} {`);
    for (const [at, props] of Object.entries(frames)) {
      const body = Object.entries(props)
        .map(([prop, value]) => `${prop}: ${value};`)
        .join(" ");
      lines.push(`    ${at} { ${body} }`);
    }
    lines.push("  }");
  }

  // Breakpoints are static: media queries can't read custom properties.
  const breakpoints = Object.entries(breakpoint).map(([name, value]) =>
    decl(`--breakpoint-${name}`, value),
  );

  return (
    banner +
    '@import "./tokens.css";\n\n' +
    '@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));\n\n' +
    "/* Remove Tailwind's default scales so only design-system values exist. */\n" +
    block("@theme", [
      "  --color-*: initial;",
      "  --radius-*: initial;",
      "  --shadow-*: initial;",
      "  --breakpoint-*: initial;",
      ...breakpoints,
    ]) +
    "\n" +
    block("@theme inline", lines)
  );
}

function tokensJson(): string {
  const resolvedSemantic = Object.fromEntries(
    Object.entries(semanticColors).map(([name, token]) => [
      name,
      { light: token.light, dark: token.dark, description: token.description },
    ]),
  );
  return JSON.stringify(
    {
      color: { base, palette, semantic: resolvedSemantic },
      spacingUnit,
      radius,
      fontFamily,
      fontWeight,
      fontSize,
      shadow,
      duration,
      easing,
      zIndex,
      breakpoint,
    },
    null,
    2,
  );
}

await mkdir(outDir, { recursive: true });
await Promise.all([
  writeFile(join(outDir, "tokens.css"), tokensCss()),
  writeFile(join(outDir, "theme.css"), themeCss()),
  writeFile(join(outDir, "tokens.json"), tokensJson() + "\n"),
]);
console.log(`@ledgerly/tokens → ${outDir}`);
